#!/usr/bin/env node
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { figmaToCssVar } from './lib/figma-token-utils.mjs';
import { loadVariablesDoc, parseVariablesJson } from './lib/parse-variables-json.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const src = join(root, 'src');
const strict = process.argv.includes('--strict');
const jsonOut = process.argv.includes('--json');

const variablesPath = join(root, 'variables.json');
if (!existsSync(variablesPath)) {
  console.error('Missing variables.json');
  process.exit(1);
}
const parsed = parseVariablesJson(loadVariablesDoc(variablesPath));
const manifest = {
  colorSemantic: parsed.colorSemantic,
  unit: parsed.unit,
  dimension: parsed.dimension,
  typography: parsed.typography,
  colorPrimitives: parsed.colorPrimitives,
};

const TOKEN_DEF_DIRS = [
  join(src, 'styles/tokens'),
  join(src, 'styles/themes'),
];

const EXCLUDE_PATH_RE = /[\\/](styles[\\/]tokens[\\/]|styles[\\/]themes[\\/]|components[\\/]Decorations[\\/])/;
const SOURCE_EXT_RE = /\.(css|tsx?|jsx?)$/;

const COLOR_HARD_RE = /#[0-9a-f]{3,8}\b|rgba?\(|hsla?\(/i;
const VAR_USE_RE = /var\(\s*(--q-[a-z0-9-]+)/gi;
const VAR_DEF_RE = /(--q-[a-z0-9-]+)\s*:/gi;

const ALLOW_CONTENT_RE = [
  /--q-window-close-bg-(hover|active)\s*:/i,
  /linear-gradient\(#fff\s+0\s+0\)/i,
  /rgb\(255\s+255\s+255\s*\/\s*var\(--q-button-shine/i,
  /rgb\(255\s+255\s+255\s*\/\s*0\)/i,
  /Generated by scripts\/sync-figma-tokens/i,
];

function buildWhitelist() {
  const figmaNames = [
    ...manifest.colorSemantic.map((t) => t.name),
    ...manifest.unit.map((t) => t.name),
    ...manifest.dimension.map((t) => t.name),
    ...manifest.typography.map((t) => t.name),
    ...(manifest.colorPrimitives ?? []).map((t) => t.name),
  ];

  const whitelist = new Set(figmaNames.map(figmaToCssVar));

  for (const name of figmaNames) {
    whitelist.add(figmaToCssVar(name));
  }

  const legacy = [
    '--q-white', '--q-black', '--q-transparent',
    '--q-bg-primary', '--q-bg-elevated', '--q-bg-sunken', '--q-bg-hover', '--q-bg-active',
    '--q-bg-selected', '--q-bg-accent-hover', '--q-text-link', '--q-text-link-hover',
    '--q-text-on-accent', '--q-text-on-color', '--q-border-subtle', '--q-border-overlay',
    '--q-border-hover', '--q-bg-tooltip', '--q-text-tooltip',
    '--q-rounded-none', '--q-rounded-sm', '--q-rounded-md', '--q-rounded-lg',
    '--q-rounded-xl', '--q-rounded-2xl', '--q-rounded-3xl', '--q-rounded-full',
  ];
  for (const u of manifest.unit) {
    legacy.push(`--q-space-${u.name.replace('unit/', '')}`);
  }
  for (const l of legacy) whitelist.add(l);

  const appOnly = readDefinedVarsFromDir(join(src, 'styles/tokens'))
    .concat(readDefinedVarsFromFile(join(src, 'styles/tokens/effects.css')))
    .filter((v) => v.startsWith('--q-') && !whitelist.has(v));

  for (const v of appOnly) {
    if (v.startsWith('--q-sidebar-') || v.startsWith('--q-tab') || v.startsWith('--q-button-')
      || v.startsWith('--q-editor-') || v.startsWith('--q-search-') || v.startsWith('--q-empty-')
      || v.startsWith('--q-window-') || v.startsWith('--q-icon-button-') || v.startsWith('--q-titlebar-')
      || v.startsWith('--q-backlinks-') || v.startsWith('--q-book-') || v.startsWith('--q-shadow-')
      || v.startsWith('--q-duration-') || v.startsWith('--q-ease-') || v.startsWith('--q-z-')
      || v.startsWith('--q-opacity-') || v.startsWith('--q-base-')
      || v.startsWith('--q-transition-') || v.startsWith('--q-caret-') || v.startsWith('--q-scrollbar-')
      || v.startsWith('--q-selection-') || v.startsWith('--q-tabs-') || v.startsWith('--q-radius-')
      || v.startsWith('--q-border-0') || v.startsWith('--q-border-2') || v.startsWith('--q-border-3')
      || v.startsWith('--q-border-4') || v.startsWith('--q-font-size-') || v.startsWith('--q-font-family-')
      || v.startsWith('--q-font-weight-') || v.startsWith('--q-line-height-') || v.startsWith('--q-tracking-')
      || v.startsWith('--q-size-') || v.startsWith('--q-space-')) {
      whitelist.add(v);
    }
  }

  return whitelist;
}

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (SOURCE_EXT_RE.test(entry)) out.push(full);
  }
  return out;
}

function readDefinedVarsFromFile(file) {
  const text = readFileSync(file, 'utf8');
  const vars = [];
  for (const match of text.matchAll(VAR_DEF_RE)) vars.push(match[1]);
  return vars;
}

function readDefinedVarsFromDir(dir) {
  const vars = [];
  for (const file of walk(dir)) {
    if (file.includes('figma-tokens')) continue;
    vars.push(...readDefinedVarsFromFile(file));
  }
  return vars;
}

function collectDefinedFigmaVars() {
  const tokenFiles = [
    'colors.css', 'unit.css', 'dimension.css', 'typography.css', 'semantic.css',
  ];
  const defined = new Set();
  for (const file of tokenFiles) {
    for (const v of readDefinedVarsFromFile(join(src, 'styles/tokens', file))) {
      defined.add(v);
    }
  }
  for (const v of readDefinedVarsFromFile(join(src, 'styles/themes/dark.css'))) {
    defined.add(v);
  }
  return defined;
}

function analyze() {
  const whitelist = buildWhitelist();
  const definedInCss = collectDefinedFigmaVars();
  const files = walk(src).filter((f) => !EXCLUDE_PATH_RE.test(f));

  const hardcodedColors = [];
  const unknownVars = new Map();
  const usedVars = new Map();

  for (const file of files) {
    const rel = relative(root, file).replace(/\\/g, '/');
    const lines = readFileSync(file, 'utf8').split('\n');
    lines.forEach((line, idx) => {
      const lineNo = idx + 1;
      if (COLOR_HARD_RE.test(line)) {
        const entry = `${rel}:${lineNo}: ${line.trim()}`;
        const allowed = ALLOW_CONTENT_RE.some((re) => re.test(entry));
        if (!allowed) hardcodedColors.push({ file: rel, line: lineNo, text: line.trim() });
      }
      for (const match of line.matchAll(VAR_USE_RE)) {
        const name = match[1];
        usedVars.set(name, (usedVars.get(name) ?? 0) + 1);
        if (!whitelist.has(name)) {
          const list = unknownVars.get(name) ?? [];
          list.push({ file: rel, line: lineNo, text: line.trim() });
          unknownVars.set(name, list);
        }
      }
    });
  }

  const expectedFigma = new Set([
    ...manifest.colorSemantic.map((t) => figmaToCssVar(t.name)),
    ...manifest.unit.map((t) => figmaToCssVar(t.name)),
    ...manifest.dimension.map((t) => figmaToCssVar(t.name)),
    ...manifest.typography.map((t) => figmaToCssVar(t.name)),
    ...(manifest.colorPrimitives ?? []).map((t) => figmaToCssVar(t.name)),
  ]);

  const missingInProd = [...expectedFigma].filter((v) => !definedInCss.has(v)).sort();
  const unusedFigma = [...expectedFigma].filter((v) => !usedVars.has(v)).sort();

  return {
    summary: {
      hardcodedColors: hardcodedColors.length,
      unknownVarUsages: unknownVars.size,
      missingInProd: missingInProd.length,
      unusedFigmaTokens: unusedFigma.length,
      whitelistSize: whitelist.size,
    },
    hardcodedColors,
    unknownVars: Object.fromEntries(
      [...unknownVars.entries()].sort(([a], [b]) => a.localeCompare(b)),
    ),
    missingInProd,
    unusedFigma: unusedFigma.slice(0, 40),
  };
}

const report = analyze();

if (jsonOut) {
  console.log(JSON.stringify(report, null, 2));
} else {
  console.log('=== Design Token Audit ===\n');
  console.log(`Hardcoded colors in UI:     ${report.summary.hardcodedColors}`);
  console.log(`Unknown --q-* usages:       ${report.summary.unknownVarUsages}`);
  console.log(`Figma tokens missing prod:  ${report.summary.missingInProd}`);
  console.log(`Unused Figma tokens:        ${report.summary.unusedFigmaTokens} (showing 40)`);
  console.log(`Whitelist size:             ${report.summary.whitelistSize}\n`);

  if (report.hardcodedColors.length) {
    console.log('--- Hardcoded colors ---');
    for (const hit of report.hardcodedColors.slice(0, 50)) {
      console.log(`${hit.file}:${hit.line}: ${hit.text}`);
    }
    if (report.hardcodedColors.length > 50) {
      console.log(`... and ${report.hardcodedColors.length - 50} more`);
    }
    console.log('');
  }

  if (Object.keys(report.unknownVars).length) {
    console.log('--- Unknown CSS variables (not in Figma whitelist) ---');
    for (const [name, hits] of Object.entries(report.unknownVars).slice(0, 30)) {
      console.log(`\n${name} (${hits.length} uses)`);
      for (const hit of hits.slice(0, 3)) {
        console.log(`  ${hit.file}:${hit.line}`);
      }
    }
    console.log('');
  }

  if (report.missingInProd.length) {
    console.log('--- Figma tokens missing in prod CSS ---');
    for (const v of report.missingInProd.slice(0, 30)) console.log(`  ${v}`);
    if (report.missingInProd.length > 30) {
      console.log(`  ... and ${report.missingInProd.length - 30} more`);
    }
    console.log('');
  }
}

const fail = strict && (
  report.summary.hardcodedColors > 0 || report.summary.unknownVarUsages > 0
);
process.exit(fail ? 1 : 0);
